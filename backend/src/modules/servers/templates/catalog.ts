/** Shared variable blocks, so a hundred entries cannot drift on MAIN_FILE. */
const mainFile = (dflt: string, what = 'Main file') => ({
  key: 'MAIN_FILE',
  name: what,
  description: 'The file that starts your app, relative to the server root.',
  defaultValue: dflt,
  required: true,
});

const extraArgs = (key: string, what: string) => ({
  key,
  name: `${what} arguments`,
  description: `Extra arguments passed to ${what}.`,
  defaultValue: '',
  required: false,
});

/** Web templates publish one TCP port; bots publish none (outbound only). */
