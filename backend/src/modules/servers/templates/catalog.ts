/** Fast id lookup. */
export const TEMPLATE_BY_ID: ReadonlyMap<string, TemplateDefinition> = new Map(
  TEMPLATES.map((t) => [t.id, t]),
);

export function templateById(id: string): TemplateDefinition {
  const t = TEMPLATE_BY_ID.get(id);
  if (!t) throw new Error(`unknown template: ${id}`);
  return t;
}

/**
 * Templates a client may currently create from. `enabled: false` and
 * `status: 'deprecated'` entries are hidden from the picker but stay
 * resolvable, so a server already running on one is never bricked.
 */
export function creatableTemplates(): TemplateDefinition[] {
  return TEMPLATES.filter((t) => t.enabled && t.status !== 'disabled' && t.status !== 'deprecated');
}

/**
 * The template a LEGACY server row (one created before templates existed) maps
 * to. Its `runtime` column is the only thing such a row has, so the catalog
 * needs a deterministic answer for each of the four original runtimes.
 */
const LEGACY_BY_RUNTIME: Record<string, string> = {
  'Node.js': 'nodejs-npm',
  Python: 'python-pip',
  Bun: 'bun-app',
  PHP: 'php-cli',
  Go: 'go-app',
  Rust: 'rust-app',
  Java: 'java-jar',
  Ruby: 'ruby-app',
  '.NET': 'dotnet-app',
  Deno: 'deno-app',
};

/** Legacy template for a runtime-only row. Falls back to Node.js never failing. */
export function legacyTemplateFor(runtime: string): TemplateDefinition | undefined {
  const id = LEGACY_BY_RUNTIME[runtime];
  return id ? TEMPLATE_BY_ID.get(id) : undefined;
}

/** Which runtime image a template resolves to, for the admin panel. */
export function runtimeOfTemplate(id: string): string {
  const t = templateById(id);
  if (!RUNTIME_IMAGES[t.runtime as keyof typeof RUNTIME_IMAGES]) {
    throw new Error(`template ${id} references unknown runtime ${t.runtime}`);
  }
  return t.runtime;
}