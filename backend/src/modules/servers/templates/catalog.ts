/**
 * The template catalog — one source of truth for what the platform can host.
 *
 * Before this file the platform had no catalog: `RUNTIME_IMAGES` was both the
 * image allowlist AND the list of things a client could create, which is why
 * "Node.js" had to serve a Discord bot, a Next.js site and a cron worker alike,
 * and why Go, Rust, Java and every game were simply absent.
 *
 * Every entry here is DATA. Nothing in this file is executed by itself: install
 * and build work is expressed as declarative steps (`templates/steps.ts`) and
 * startup is a `{{VAR}}` template validated by `validateStartup`.
 *
 * Two rules govern what may appear here:
 *
 *  1. A template may only reference a runtime that exists in `RUNTIME_IMAGES`.
 *     Templates never carry an image of their own, so the allowlist that keeps
 *     the host safe cannot be widened by adding a template. The schema check
 *     enforces this.
 *
 *  2. `status: 'verified'` is a CLAIM that must be backed by a run of
 *     `test/templates/` against real containers. It is deliberately NOT claimed
 *     at authoring time — entries ship `unverified` and only the integration
 *     suite promotes them. That is the difference between this catalog and a
 *     wish list.
 */

